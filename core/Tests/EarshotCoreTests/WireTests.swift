import XCTest
@testable import EarshotCore

final class WireTests: XCTestCase {
    func testRoundTripAllPacketTypes() throws {
        let ps: [Packet] = [
            .audio(PacketHeader(type: .audio, seq: 7, clipMs: 123456), adpcm: [UInt8](repeating: 0x5A, count: Wire.audioPayloadSize)),
            .tap(PacketHeader(type: .tap, seq: 2, clipMs: 99), TapPayload(gesture: .mark, source: .button, pressClipMs: 95)),
            .state(PacketHeader(type: .state, seq: 1, clipMs: 5), StatePayload(state: .listening, flags: 1)),
            .state(PacketHeader(type: .state, seq: 1, clipMs: 5), StatePayload(state: .listening, flags: 1, version: 1)),
            .clock(PacketHeader(type: .clock, seq: 0, clipMs: 0), epochMs: 1_763_233_200_000),
            .ack(PacketHeader(type: .ack, seq: 0, clipMs: 0), ackedSeq: 65535),
        ]
        for p in ps { XCTAssertEqual(try Wire.decode(Wire.encode(p)), p) }
        XCTAssertEqual(Wire.encode(ps[0]).count, 7 + 164)
        XCTAssertEqual(Wire.encode(ps[1]), [0x02, 2, 0, 99, 0, 0, 0, 0, 0, 95, 0, 0, 0])
        // knock (1) and snap (2) tap sources are retired: the button is the only tap input
        for retired: UInt8 in [1, 2] {
            XCTAssertThrowsError(try Wire.decode([0x02, 2, 0, 99, 0, 0, 0, 0, retired, 95, 0, 0, 0]))
        }
    }

    func testDeframerHandlesPartialChunks() {
        let p = Packet.tap(PacketHeader(type: .tap, seq: 3, clipMs: 10), TapPayload(gesture: .yes, source: .button, pressClipMs: 9))
        let bytes = Wire.frame(p) + Wire.frame(p)
        var d = StreamDeframer()
        XCTAssertEqual(d.push(Array(bytes[0..<5])).count, 0)
        XCTAssertEqual(d.push(Array(bytes[5...])).count, 2)
    }

    func testADPCMQuality() {
        var pcm: [Int16] = []
        for i in 0..<Wire.samplesPerFrame * 10 { pcm.append(Int16(9000 * sin(Double(i) * 2 * .pi * 440 / 16000))) }
        var st = IMAADPCM.State()
        var dec: [Int16] = []
        for f in 0..<10 {
            let block = IMAADPCM.encodeBlock(Array(pcm[(f * 320)..<((f + 1) * 320)]), state: &st)
            XCTAssertEqual(block.count, Wire.audioPayloadSize)
            dec += IMAADPCM.decodeBlock(block)
        }
        var sig = 0.0, err = 0.0
        for i in 320..<pcm.count { sig += Double(pcm[i]) * Double(pcm[i]); let e = Double(pcm[i]) - Double(dec[i]); err += e * e }
        XCTAssertGreaterThan(10 * log10(sig / err), 20, "ADPCM SNR too low")
    }

    /// Bit-exact match with firmware/common/adpcm.c (vector generated by firmware/common/test/gen_vectors.c).
    func testADPCMMatchesFirmwareVector() throws {
        let url = TestEnv.repoRoot.appendingPathComponent("firmware/common/test/adpcm_vector.bin")
        guard let data = try? Data(contentsOf: url) else { throw XCTSkip("firmware vector not generated") }
        var pcm: [Int16] = []
        for i in 0..<320 { pcm.append(Int16(12000 * sin(Double(i) * 2 * .pi * 300 / 16000) + 3000 * sin(Double(i) * 2 * .pi * 1700 / 16000))) }
        var st = IMAADPCM.State()
        let block = IMAADPCM.encodeBlock(pcm, state: &st)
        XCTAssertEqual(block, [UInt8](data.prefix(164)))
    }

    func testAssemblerReordersDedupesAndReportsGaps() {
        let pcm = burstPCM(seconds: 1, bursts: [(0, 1)])
        var packets = ReplayFile.packets(fromPCM: pcm, taps: [TapInput(clipMs: 1200, source: "button")], startClipMs: 1000)
        let audioIdx = packets.indices.filter { if case .audio = packets[$0] { return true }; return false }
        packets.swapAt(audioIdx[3], audioIdx[4])           // reorder
        packets.append(packets[audioIdx[10]])               // duplicate (resend)
        packets.remove(at: audioIdx[20])                    // drop one frame
        let asm = AudioAssembler(reorderDepth: Int.max)
        var out: [Int16] = []
        for p in packets { out += asm.push(p) }
        out += asm.finish()
        XCTAssertEqual(out.count, 50 * 320)
        XCTAssertEqual(asm.gaps.count, 1)
        XCTAssertEqual(asm.gaps[0].missingFrames, 1)
        XCTAssertEqual(asm.duplicates, 1)
        XCTAssertEqual(asm.taps.map(\.gesture), ["start", "yes", "mark", "stop"])
    }

    func testSeqUnwrap() {
        var u = SeqUnwrapper()
        XCTAssertEqual(u.unwrap(65534), 65534)
        XCTAssertEqual(u.unwrap(65535), 65535)
        XCTAssertEqual(u.unwrap(0), 65536)
        XCTAssertEqual(u.unwrap(65535), 65535) // late duplicate stays before
    }

    func testRingBufferDiscardAndWipe() {
        let r = PCMRingBuffer(capacitySeconds: 1)
        r.append([Int16](repeating: 5, count: 20000))
        XCTAssertEqual(r.endSample, 20000)
        XCTAssertEqual(r.baseSample, 4000)
        r.discard(before: 10000)
        XCTAssertEqual(r.read(from: 0, to: 20000).count, 10000)
        r.wipe()
        XCTAssertEqual(r.read(from: 0, to: 30000).count, 0)
    }

    func testVADFindsBursts() {
        let pcm = burstPCM(seconds: 10, bursts: [(1, 2.5), (5, 6)])
        let v = EnergyVAD()
        let chunks = v.push(pcm) + v.finish()
        XCTAssertEqual(chunks.count, 2)
        XCTAssertEqual(Double(chunks[0].startMs) / 1000, 0.8, accuracy: 0.15)
    }
}
