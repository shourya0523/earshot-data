import Foundation

/// Agency/unit setup values. These are configuration, not things heard on a
/// call; defaults are obvious placeholders. Set them via `"agency"` in the
/// pipeline config (or app settings).
public struct NEMSISAgency: Codable, Equatable, Sendable {
    public var stateId = "EARSHOT-DEMO"        // dAgency.01
    public var number = "DEMO001"              // dAgency.02 / eResponse.01
    public var stateCode = "25"                // dAgency.04 (ANSI state code; 25 = Massachusetts)
    public var vehicle = "DEMO-UNIT"           // eResponse.13
    public var callSign = "MEDIC-DEMO"         // eResponse.14
    public var serviceType = "2205001"         // eResponse.05 Emergency Response (Primary Response Area)
    public var capability = "2207015"          // eResponse.07 Ground Transport (ALS Equipped)
    public init() {}
}

/// NEMSIS v3.5.1 EMSDataSet export, generated by code from events only.
/// Every required section and element is present in XSD order; anything not
/// heard is `xsi:nil="true" NV="7701003"` (Not Recorded). A few required
/// elements cannot be nil in the schema (agency ids, eTimes.03, eTimes.13,
/// eDispatch.01, eDisposition.27); those come from agency config or are
/// placeholders listed in a REQUIRES CREW ENTRY comment at the top.
/// Checked with xmllint against the vendored XSDs (core/Tests/.../nemsis_xsd).
public enum NEMSISExport {
    public static let unvalidatedBanner = "Schema-checked against NEMSIS v3.5.1 XSD (not Schematron/state rules). Draft until the medic signs."
    static let NR = #"xsi:nil="true" NV="7701003""#

    static let dispatchCodes: [(String, String)] = [
        ("chest pain", "2301021"), ("breathing", "2301013"), ("shortness of breath", "2301013"), ("fall", "2301033"), ("fell", "2301033"),
        ("abdominal", "2301001"), ("allergic", "2301003"), ("assault", "2301007"), ("back pain", "2301011"), ("burn", "2301015"),
        ("choking", "2301023"), ("seizure", "2301025"), ("convulsion", "2301025"), ("diabetic", "2301027"), ("headache", "2301037"),
        ("heart", "2301041"), ("cardiac", "2301041"), ("bleeding", "2301045"), ("hemorrhage", "2301045"), ("laceration", "2301045"),
        ("pregnan", "2301057"), ("labor", "2301057"), ("psychiatric", "2301059"), ("behavioral", "2301059"), ("sick", "2301061"),
        ("unresponsive", "2301077"), ("unconscious", "2301077"), ("syncope", "2301077"), ("fainted", "2301077"), ("passed out", "2301077"),
        ("mvc", "2301069"), ("mva", "2301069"), ("motor vehicle", "2301069"), ("injur", "2301073"), ("trauma", "2301073"),
    ]

    public static func render(_ m: ChartModel, events: [EarshotEvent], dict: EMSDictionary, agency: NEMSISAgency = NEMSISAgency(),
                              softwareVersion: String = "0.1.0") -> RenderedDoc {
        var x: [String] = []
        var crewEntry: [String] = []
        func esc(_ s: String) -> String {
            s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
                .replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;")
        }
        func el(_ ind: Int, _ name: String, _ v: String?, _ note: String? = nil) {
            let pad = String(repeating: "  ", count: ind)
            if let v = v { x.append("\(pad)<\(name)>\(esc(v))</\(name)>" + (note.map { "<!-- \($0) -->" } ?? "")) }
            else { x.append("\(pad)<\(name) \(NR)/>") }
        }
        func open(_ ind: Int, _ name: String, _ note: String? = nil) { x.append(String(repeating: "  ", count: ind) + "<\(name)>" + (note.map { "<!-- \($0) -->" } ?? "")) }
        func close(_ ind: Int, _ name: String) { x.append(String(repeating: "  ", count: ind) + "</\(name)>") }

        let callStart = m.clock.iso(0)
        let lastT = events.map(\.tMs).max() ?? 0
        x.append(#"<?xml version="1.0" encoding="UTF-8"?>"#)
        x.append("<!-- \(unvalidatedBanner) -->")
        let crewIdx = x.count; x.append("")   // REQUIRES CREW ENTRY comment filled in at the end
        x.append("<!-- Every element cites the Earshot event it came from. Values not heard are nil/Not Recorded. -->")
        x.append(#"<EMSDataSet xmlns="http://www.nemsis.org" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.nemsis.org https://nemsis.org/media/nemsis_v3/release-3.5.1/XSDs/NEMSIS_XSDs/EMSDataSet_v3.xsd">"#)
        open(1, "Header")
        open(2, "DemographicGroup")
        el(3, "dAgency.01", agency.stateId); el(3, "dAgency.02", agency.number); el(3, "dAgency.04", agency.stateCode)
        close(2, "DemographicGroup")
        x.append("    <PatientCareReport UUID=\"\(uuid(m.callId))\">")
        // eRecord
        open(3, "eRecord")
        el(4, "eRecord.01", "PCR-" + m.callId)
        open(4, "eRecord.SoftwareApplicationGroup")
        el(5, "eRecord.02", "Earshot"); el(5, "eRecord.03", "Earshot"); el(5, "eRecord.04", softwareVersion)
        close(4, "eRecord.SoftwareApplicationGroup")
        close(3, "eRecord")
        // eResponse
        open(3, "eResponse")
        open(4, "eResponse.AgencyGroup"); el(5, "eResponse.01", agency.number); close(4, "eResponse.AgencyGroup")
        el(4, "eResponse.03", nil); el(4, "eResponse.04", nil)
        open(4, "eResponse.ServiceGroup"); el(5, "eResponse.05", agency.serviceType); close(4, "eResponse.ServiceGroup")
        el(4, "eResponse.07", agency.capability)
        for k in 8...12 { el(4, "eResponse.\(String(format: "%02d", k))", nil) }
        el(4, "eResponse.13", agency.vehicle); el(4, "eResponse.14", agency.callSign)
        let mode = m.transport.compactMap { $0.fields["mode"] }.first
        let emergent = mode.map { $0.contains("lights") || $0.contains("code 3") || $0.contains("code three") || $0 == "emergent" }
        el(4, "eResponse.23", emergent == false ? "2223005" : "2223001", emergent == nil ? "PLACEHOLDER: response mode not heard (assumed emergent)" : "from transport mode as heard")
        if emergent == nil { crewEntry.append("eResponse.23 response mode") }
        el(4, "eResponse.24", nil)
        close(3, "eResponse")
        // eDispatch
        open(3, "eDispatch")
        let dr = m.dispatch?.text.lowercased() ?? ""
        let dcode = NEMSISExport.dispatchCodes.first { dr.contains($0.0) }?.1
        el(4, "eDispatch.01", dcode ?? "2301051", dcode == nil ? "PLACEHOLDER: dispatch reason not heard / not mapped (No Other Appropriate Choice)" : "\(m.dispatch?.events.joined(separator: ",") ?? ""): heard \"\(esc(m.dispatch?.text ?? ""))\"")
        if dcode == nil { crewEntry.append("eDispatch.01 dispatch reason") }
        el(4, "eDispatch.02", nil)
        close(3, "eDispatch")
        // eTimes
        open(3, "eTimes")
        el(4, "eTimes.01", nil)
        el(4, "eTimes.03", callStart, "PLACEHOLDER: call start on the iPad, not the dispatch notification time")
        crewEntry.append("eTimes.03 unit notified by dispatch")
        el(4, "eTimes.05", nil)
        el(4, "eTimes.06", m.onScene?.time, m.onScene.map { "\($0.id): on scene (heard)" })
        el(4, "eTimes.07", nil)
        el(4, "eTimes.09", m.departed?.time, m.departed.map { "\($0.id): left scene / transporting (heard)" })
        el(4, "eTimes.11", m.arrival?.time, m.arrival.map { "\($0.id): arrival, \($0.fields["method"] ?? "")" })
        el(4, "eTimes.12", m.handoff?.time, m.handoff.map { "\($0.id): transfer of care, \($0.fields["method"] ?? "")" })
        if let w = m.wallTimeMs { x.append("        <!-- wall time = eTimes.12 - eTimes.11 = \(w / 1000) s -->") }
        if let b = m.backInService {
            el(4, "eTimes.13", b.time, "\(b.id): back in service (heard)")
        } else {
            el(4, "eTimes.13", m.handoff?.time ?? m.clock.iso(lastT), "PLACEHOLDER: unit back in service not recorded; using \(m.handoff == nil ? "last event" : "transfer of care") time")
            crewEntry.append("eTimes.13 unit back in service")
        }
        close(3, "eTimes")
        // ePatient
        open(3, "ePatient")
        for k in ["07", "08", "09"] { el(4, "ePatient.\(k)", nil) }
        el(4, "ePatient.14", nil)
        open(4, "ePatient.AgeGroup")
        if let a = m.age, Int(a.text.split(separator: " ").first ?? "") != nil {
            let months = a.text.contains("month")
            el(5, "ePatient.15", String(a.text.split(separator: " ").first!), a.events.joined(separator: ","))
            el(5, "ePatient.16", months ? "2516007" : "2516009")
        } else { el(5, "ePatient.15", nil); el(5, "ePatient.16", nil) }
        close(4, "ePatient.AgeGroup")
        if let s = m.sex {
            el(4, "ePatient.25", s.text == "male" ? "9919003" : s.text == "female" ? "9919001" : "9919005", s.events.joined(separator: ","))
        } else { el(4, "ePatient.25", nil) }
        close(3, "ePatient")
        // ePayment, eScene, eSituation, eInjury, eArrest, eHistory: not captured by Earshot
        open(3, "ePayment"); el(4, "ePayment.01", nil); el(4, "ePayment.50", nil); close(3, "ePayment")
        open(3, "eScene"); for k in ["01", "06", "07", "08", "09", "18", "19", "21"] { el(4, "eScene.\(k)", nil) }; close(3, "eScene")
        open(3, "eSituation"); for k in ["01", "02", "07", "08", "09", "10", "11", "12", "13", "18", "20"] { el(4, "eSituation.\(k)", nil) }; close(3, "eSituation")
        open(3, "eInjury"); for k in ["01", "03", "04"] { el(4, "eInjury.\(k)", nil) }; close(3, "eInjury")
        open(3, "eArrest"); for k in ["01", "02", "03", "04", "07", "09", "11", "12", "14", "16", "17", "18", "20", "21", "22"] { el(4, "eArrest.\(k)", nil) }; close(3, "eArrest")
        open(3, "eHistory"); el(4, "eHistory.01", nil); el(4, "eHistory.17", nil); close(3, "eHistory")
        // eNarrative
        open(3, "eNarrative"); el(4, "eNarrative.01", narrative(m)); close(3, "eNarrative")
        // eVitals
        open(3, "eVitals")
        let vitals = m.vitals.isEmpty ? [nil] : m.vitals.map { Optional($0) }
        for v in vitals {
            let f = v?.fields ?? [:]
            open(4, "eVitals.VitalGroup", v.map { "\($0.id)" })
            el(5, "eVitals.01", v?.time); el(5, "eVitals.02", v == nil ? nil : "9923001")
            open(5, "eVitals.CardiacRhythmGroup"); el(6, "eVitals.03", nil); el(6, "eVitals.04", nil); el(6, "eVitals.05", nil); close(5, "eVitals.CardiacRhythmGroup")
            open(5, "eVitals.BloodPressureGroup")
            el(6, "eVitals.06", f["bp_systolic"])
            if let d = f["bp_diastolic"] { el(6, "eVitals.07", d) }
            if f["bp_method"] == "palpation" { el(6, "eVitals.08", "3308009", "cuff-manual palpated only") }
            close(5, "eVitals.BloodPressureGroup")
            open(5, "eVitals.HeartRateGroup"); el(6, "eVitals.10", f["heart_rate"]); close(5, "eVitals.HeartRateGroup")
            el(5, "eVitals.12", f["spo2"]); el(5, "eVitals.14", f["resp_rate"]); el(5, "eVitals.16", f["etco2"])
            el(5, "eVitals.18", f["glucose"].flatMap { Int($0) != nil ? $0 : nil })
            open(5, "eVitals.GlasgowScoreGroup")
            for k in ["19", "20", "21", "22"] { el(6, "eVitals.\(k)", nil) }
            if let g = f["gcs"] { el(6, "eVitals.23", g) }
            close(5, "eVitals.GlasgowScoreGroup")
            if let t = f["temp"], let d = Double(t) {
                let c = d > 50 ? ((d - 32) * 5 / 9 * 10).rounded() / 10 : d
                open(5, "eVitals.TemperatureGroup"); el(6, "eVitals.24", String(c)); close(5, "eVitals.TemperatureGroup")
            }
            el(5, "eVitals.26", nil)
            open(5, "eVitals.PainScaleGroup"); el(6, "eVitals.27", f["pain"]); close(5, "eVitals.PainScaleGroup")
            open(5, "eVitals.StrokeScaleGroup"); el(6, "eVitals.29", nil); el(6, "eVitals.30", nil); close(5, "eVitals.StrokeScaleGroup")
            el(5, "eVitals.31", nil)
            close(4, "eVitals.VitalGroup")
        }
        close(3, "eVitals")
        // eProtocols
        open(3, "eProtocols"); open(4, "eProtocols.ProtocolGroup"); el(5, "eProtocols.01", nil); close(4, "eProtocols.ProtocolGroup"); close(3, "eProtocols")
        // eMedications
        open(3, "eMedications")
        let meds = m.meds.isEmpty ? [nil] : m.meds.map { Optional($0) }
        for e in meds {
            let f = e?.fields ?? [:]
            let drug = f["drug"].flatMap { dict.drug(named: $0) }
            open(4, "eMedications.MedicationGroup", e.map { "\($0.id): \(esc(f["drug"] ?? ""))" })
            el(5, "eMedications.01", e?.time); el(5, "eMedications.02", e == nil ? nil : "9923001")
            if let rx = drug?.rxcui { x.append("          <eMedications.03 CodeType=\"9924003\">\(rx)</eMedications.03>") } else { el(5, "eMedications.03", nil) }
            el(5, "eMedications.04", f["route"].flatMap { dict.formulary.routes[$0]?.nemsis_code })
            open(5, "eMedications.DosageGroup")
            el(6, "eMedications.05", f["dose"])
            // unit only when spoken; an unspoken unit stays Not Recorded even if the protocol suggests one
            el(6, "eMedications.06", f["unit"].flatMap { dict.formulary.units[$0]?.nemsis_code })
            close(5, "eMedications.DosageGroup")
            el(5, "eMedications.07", nil); el(5, "eMedications.08", nil); el(5, "eMedications.10", nil)
            close(4, "eMedications.MedicationGroup")
        }
        close(3, "eMedications")
        // eProcedures (SNOMED codes not mapped yet: eProcedures.03 Not Recorded; name in comment)
        open(3, "eProcedures")
        let procs = m.procedures.isEmpty ? [nil] : m.procedures.map { Optional($0) }
        for e in procs {
            open(4, "eProcedures.ProcedureGroup", e.map { "\($0.id): \(esc($0.fields["procedure"] ?? "")); SNOMED code not mapped yet" })
            el(5, "eProcedures.01", e?.time); el(5, "eProcedures.02", e == nil ? nil : "9923001")
            for k in ["03", "05", "06", "07", "08", "10"] { el(5, "eProcedures.\(k)", nil) }
            close(4, "eProcedures.ProcedureGroup")
        }
        close(3, "eProcedures")
        // eDisposition
        open(3, "eDisposition")
        open(4, "eDisposition.DestinationGroup")
        if let d = m.transport.compactMap({ $0.fields["destination"] }).first {
            el(5, "eDisposition.01", d, "destination as heard")
        }
        el(5, "eDisposition.05", nil); el(5, "eDisposition.06", nil); el(5, "eDisposition.07", nil)
        close(4, "eDisposition.DestinationGroup")
        open(4, "eDisposition.IncidentDispositionGroup")
        el(5, "eDisposition.27", "4227001", "Patient Contact Made (a consented call implies contact)")
        el(5, "eDisposition.28", nil); el(5, "eDisposition.29", nil); el(5, "eDisposition.30", nil)
        close(4, "eDisposition.IncidentDispositionGroup")
        for k in 16...23 { el(4, "eDisposition.\(k)", nil) }
        open(4, "eDisposition.HospitalTeamActivationGroup"); el(5, "eDisposition.24", nil); el(5, "eDisposition.25", nil); close(4, "eDisposition.HospitalTeamActivationGroup")
        el(4, "eDisposition.32", nil)
        close(3, "eDisposition")
        // eOutcome (hospital data; never known to EMS at handoff)
        open(3, "eOutcome")
        el(4, "eOutcome.01", nil); el(4, "eOutcome.02", nil)
        open(4, "eOutcome.EmergencyDepartmentProceduresGroup"); el(5, "eOutcome.09", nil); el(5, "eOutcome.19", nil); close(4, "eOutcome.EmergencyDepartmentProceduresGroup")
        el(4, "eOutcome.10", nil); el(4, "eOutcome.11", nil)
        open(4, "eOutcome.HospitalProceduresGroup"); el(5, "eOutcome.12", nil); el(5, "eOutcome.20", nil); close(4, "eOutcome.HospitalProceduresGroup")
        el(4, "eOutcome.13", nil); el(4, "eOutcome.16", nil); el(4, "eOutcome.18", nil)
        close(3, "eOutcome")
        x.append("    </PatientCareReport>")
        close(1, "Header")
        x.append("</EMSDataSet>")
        x[crewIdx] = "<!-- REQUIRES CREW ENTRY (placeholders the schema does not allow to be empty): \(crewEntry.joined(separator: "; ")) -->"
        return RenderedDoc(name: "nemsis.xml", text: x.joined(separator: "\n") + "\n")
    }

    static func narrative(_ m: ChartModel) -> String {
        Renderers.chart(m).text.replacingOccurrences(of: "**", with: "")
    }

    /// Deterministic UUID-shaped id from the call id (FNV-1a based).
    static func uuid(_ s: String) -> String {
        var h1: UInt64 = 0xcbf29ce484222325, h2: UInt64 = 0x84222325cbf29ce4
        for b in s.utf8 { h1 = (h1 ^ UInt64(b)) &* 0x100000001b3; h2 = (h2 ^ UInt64(b)) &* 0x100000001b3 &+ 7 }
        let hex = String(format: "%016llx%016llx", h1, h2)
        let c = Array(hex)
        return "\(String(c[0..<8]))-\(String(c[8..<12]))-4\(String(c[13..<16]))-a\(String(c[17..<20]))-\(String(c[20..<32]))"
    }
}
