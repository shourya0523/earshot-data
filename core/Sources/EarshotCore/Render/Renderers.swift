import Foundation

/// All four outputs are rendered by code from events. No model writes these.
/// Each renderer returns the document plus a line -> event-id map so the app
/// can show the receipt for any tapped line.
public struct RenderedDoc: Sendable {
    public var name: String
    public var text: String
    /// line index -> event ids cited on that line
    public var receipts: [Int: [String]]
    public init(name: String, text: String) {
        self.name = name; self.text = text
        var r: [Int: [String]] = [:]
        let rx = try! NSRegularExpression(pattern: #"\be\d+\b"#)
        for (i, line) in text.split(separator: "\n", omittingEmptySubsequences: false).enumerated() {
            let ns = String(line) as NSString
            guard let open = String(line).range(of: "[e") else { continue }
            _ = open
            let ids = rx.matches(in: String(line), range: NSRange(location: 0, length: ns.length)).map { ns.substring(with: $0.range) }
            if !ids.isEmpty { r[i] = ids }
        }
        receipts = r
    }
}

public enum Renderers {
    static let footer = """

    ---
    _Draft generated by Earshot from what was heard and tapped. Values marked "not heard" were not captured. \
    Earshot documents only; it does not diagnose or advise. \
    Nothing is filed until the medic reviews and signs._
    """

    // MARK: SOAP

    public static func soap(_ m: ChartModel) -> RenderedDoc {
        var L: [String] = []
        L.append("# SOAP note — call \(m.callId)")
        L.append("")
        L.append("## S — Subjective")
        L.append("- Dispatched for: \(ChartModel.show(m.dispatch))")
        if m.found != nil || m.chiefComplaint != nil {
            L.append("- Found / chief complaint (as heard): \(ChartModel.show(m.found ?? m.chiefComplaint))")
        } else {
            L.append("- Chief complaint: \(ChartModel.notHeard)")
        }
        if m.dispatchChanged { L.append("- ⚠︎ Dispatch reason differs from what was found on scene.") }
        L.append("- Symptoms reported: \(ChartModel.list(m.symptoms))")
        L.append("- Symptoms denied: \(ChartModel.list(m.denied))")
        L.append("- History: \(ChartModel.list(m.history))")
        L.append("- Allergies: \(ChartModel.list(m.allergies))")
        L.append("- Home medications: \(ChartModel.list(m.homeMeds))")
        if !m.ptaMeds.isEmpty { L.append("- Taken before EMS arrival: \(ChartModel.list(m.ptaMeds))") }
        L.append("")
        L.append("## O — Objective")
        L.append("- Patient: age \(ChartModel.show(m.age)), sex \(ChartModel.show(m.sex)), weight \(ChartModel.show(m.weight))")
        L.append("- Mental status: \(ChartModel.show(m.mental)); pupils: \(ChartModel.show(m.pupils))")
        L.append("- Findings (as said by crew): \(ChartModel.list(m.findings))")
        L.append("- Vitals:")
        if m.vitals.isEmpty { L.append("  - \(ChartModel.notHeard)") }
        for v in m.vitals { L.append("  - \(m.clock.clock(v.tMs)) \(ChartModel.vitalsLine(v)) — \(ChartModel.srcLabel(v)) [\(v.id)]") }
        L.append("")
        L.append("## A — Assessment")
        L.append("- Earshot does not assess or diagnose. Condition words spoken by the crew: \(ChartModel.list(m.conditions))")
        for (k, label) in [("heart_rate", "HR"), ("spo2", "SpO2"), ("bp_systolic", "SBP"), ("resp_rate", "RR"), ("pain", "Pain"), ("glucose", "BGL")] {
            if let (a, b, ids) = m.trend(k) { L.append("- Trend \(label): \(a) → \(b)\(ChartModel.receipt(ids))") }
        }
        L.append("")
        L.append("## P — Plan / treatment")
        L.append("- Medications:")
        if m.meds.isEmpty { L.append("  - \(ChartModel.notHeard)") }
        for e in m.meds { L.append("  - " + ChartModel.medLine(e, clock: m.clock)) }
        if !m.medsNotGiven.isEmpty { L.append("- Not given / held: \(ChartModel.list(m.medsNotGiven))") }
        if !m.notDone.isEmpty { L.append("- Not done: \(ChartModel.list(m.notDone))") }
        L.append("- Procedures:")
        if m.procedures.isEmpty { L.append("  - \(ChartModel.notHeard)") }
        for e in m.procedures { L.append("  - \(m.clock.clock(e.tMs)) \(procText(e)) — \(ChartModel.srcLabel(e)) [\(e.id)]") }
        L.append("- Transport: \(transportText(m))")
        L.append("- On scene (eTimes.06): \(timeOrNot(m.onScene, m)); left scene (eTimes.09): \(timeOrNot(m.departed, m))")
        L.append("- Arrival at destination (eTimes.11): \(timeOrNot(m.arrival, m))")
        L.append("- Transfer of care (eTimes.12): \(timeOrNot(m.handoff, m))")
        L.append("- Wall time: \(m.wallTimeMs.map(ChartModel.duration) ?? ChartModel.notHeard)")
        L += openItems(m)
        return RenderedDoc(name: "soap.md", text: L.joined(separator: "\n") + footer + "\n")
    }

    // MARK: CHART

    public static func chart(_ m: ChartModel) -> RenderedDoc {
        var L: [String] = []
        L.append("# CHART narrative — call \(m.callId)")
        L.append("")
        L.append("**C — Chief complaint:** \(ChartModel.show(m.chiefComplaint ?? m.found)). Dispatched for \(ChartModel.show(m.dispatch)).")
        if m.dispatchChanged { L.append("Dispatch reason changed on scene: dispatched for \"\(m.dispatch!.text)\", found \"\((m.found ?? m.chiefComplaint)!.text)\".") }
        L.append("")
        L.append("**H — History:** Patient \(ChartModel.show(m.age)) y/o \(ChartModel.show(m.sex)), weight \(ChartModel.show(m.weight)). " +
                 "Symptoms reported: \(ChartModel.list(m.symptoms)). Denies: \(ChartModel.list(m.denied)). " +
                 "PMH: \(ChartModel.list(m.history)). Allergies: \(ChartModel.list(m.allergies)). Home meds: \(ChartModel.list(m.homeMeds)).")
        L.append("")
        L.append("**A — Assessment (findings as heard):** Mental status \(ChartModel.show(m.mental)); pupils \(ChartModel.show(m.pupils)); findings \(ChartModel.list(m.findings)). Condition words: \(ChartModel.list(m.conditions)).")
        if m.vitals.isEmpty { L.append("Vitals: \(ChartModel.notHeard).") }
        for v in m.vitals { L.append("- \(m.clock.clock(v.tMs)): \(ChartModel.vitalsLine(v)) [\(v.id)]") }
        L.append("")
        L.append("**R — Treatment:**")
        if m.meds.isEmpty && m.procedures.isEmpty { L.append("- \(ChartModel.notHeard)") }
        var rx: [(Int64, String)] = m.meds.map { ($0.tMs, "- " + ChartModel.medLine($0, clock: m.clock)) }
        rx += m.procedures.map { ($0.tMs, "- \(m.clock.clock($0.tMs)) \(procText($0)) — \(ChartModel.srcLabel($0)) [\($0.id)]") }
        L += rx.sorted { $0.0 < $1.0 }.map(\.1)
        if !m.medsNotGiven.isEmpty { L.append("- Not given / held: \(ChartModel.list(m.medsNotGiven))") }
        if !m.notDone.isEmpty { L.append("- Not done: \(ChartModel.list(m.notDone))") }
        L.append("")
        L.append("**T — Transport:** on scene \(timeOrNot(m.onScene, m)); left scene \(timeOrNot(m.departed, m)); \(transportText(m)). Arrived at destination \(timeOrNot(m.arrival, m)); care transferred \(timeOrNot(m.handoff, m)); wall time \(m.wallTimeMs.map(ChartModel.duration) ?? ChartModel.notHeard).")
        L += openItems(m)
        return RenderedDoc(name: "chart.md", text: L.joined(separator: "\n") + footer + "\n")
    }

    // MARK: IMIST-AMBO handoff card

    public static func imistAmbo(_ m: ChartModel) -> RenderedDoc {
        var L: [String] = []
        L.append("# IMIST-AMBO handoff — call \(m.callId)")
        L.append("")
        L.append("**I — Identification:** age \(ChartModel.show(m.age)), sex \(ChartModel.show(m.sex)), weight \(ChartModel.show(m.weight))")
        var mech = "dispatched for \(ChartModel.show(m.dispatch)); found \(ChartModel.show(m.found ?? m.chiefComplaint))"
        if m.dispatchChanged { mech += " ⚠︎ changed on scene" }
        L.append("**M — Mechanism / complaint:** \(mech)")
        L.append("**I — Injuries / information:** \(ChartModel.list(m.symptoms))" + (m.findings.isEmpty ? "" : "; findings: \(ChartModel.list(m.findings))") + (m.denied.isEmpty ? "" : "; denies \(ChartModel.list(m.denied))"))
        if !m.vitals.isEmpty {
            L.append("**S — Signs:**")
            for v in m.vitals { L.append("- \(m.clock.clock(v.tMs)) \(ChartModel.vitalsLine(v)) [\(v.id)]") }
        } else {
            L.append("**S — Signs:** \(ChartModel.notHeard)")
        }
        var tr: [String] = []
        for e in m.meds { tr.append(ChartModel.medLine(e, clock: m.clock)) }
        for e in m.procedures { tr.append("\(m.clock.clock(e.tMs)) \(procText(e)) [\(e.id)]") }
        for (k, label) in [("heart_rate", "HR"), ("spo2", "SpO2"), ("bp_systolic", "SBP"), ("pain", "Pain")] {
            if let (a, b, ids) = m.trend(k) { tr.append("\(label) \(a) → \(b)\(ChartModel.receipt(ids))") }
        }
        if !m.medsNotGiven.isEmpty { tr.append("Not given / held: \(ChartModel.list(m.medsNotGiven))") }
        if !m.notDone.isEmpty { tr.append("Not done: \(ChartModel.list(m.notDone))") }
        L.append("**T — Treatment & trends:**" + (tr.isEmpty ? " \(ChartModel.notHeard)" : ""))
        for t in tr { L.append("- \(t)") }
        L.append("**A — Allergies:** \(ChartModel.list(m.allergies))")
        L.append("**M — Medications (home):** \(ChartModel.list(m.homeMeds))")
        L.append("**B — Background:** \(ChartModel.list(m.history))")
        var other: [String] = []
        if let a = m.arrival { other.append("arrived \(m.clock.clock(a.tMs)) [\(a.id)]") }
        if let w = m.wallTimeMs { other.append("wall time \(ChartModel.duration(w))") }
        if !m.unlabeledTaps.isEmpty { other.append("\(m.unlabeledTaps.count) unlabeled tap(s): " + m.unlabeledTaps.map { "\(m.clock.clock($0.tMs)) [\($0.id)]" }.joined(separator: ", ")) }
        if !m.confirmItems.isEmpty { other.append("\(m.confirmItems.count) item(s) to confirm") }
        L.append("**O — Other:** " + (other.isEmpty ? "none" : other.joined(separator: "; ")))
        L.append("")
        L.append("Nurse accept: \(m.handoff.map { "\(m.clock.clock($0.tMs)) [\($0.id)]" } ?? "pending")")
        return RenderedDoc(name: "imist_ambo.md", text: L.joined(separator: "\n") + footer + "\n")
    }

    // MARK: helpers

    /// Quotes shown in drafts never carry a diagnostic term; the raw transcript keeps the words.
    static func safeQuote(_ q: String?) -> String {
        guard let q = q, !q.isEmpty else { return "(no quote)" }
        return Diagnosis.contains(q) ? "(quote has a diagnostic term; see transcript)" : "\"\(q)\""
    }

    static func procText(_ e: EarshotEvent) -> String {
        var s = e.fields["procedure"] ?? "procedure"
        if let g = e.fields["gauge"] { s += " \(g)g" }
        if let site = e.fields["site"] { s += " \(site)" }
        if let j = e.fields["energy_j"] { s += " \(j) J" }
        return s
    }
    static func transportText(_ m: ChartModel) -> String {
        let t = m.transport.filter { $0.fields["kind"] != "arrived_heard" }
        guard !t.isEmpty else { return ChartModel.notHeard }
        var parts: [String] = []
        var ids: [String] = []
        for e in t {
            if let d = e.fields["destination"] { parts.append("to \(d)") }
            if let x = e.fields["mode"] { parts.append(x) }
            if let a = e.fields["alert"] { parts.append(a) }
            if let eta = e.fields["eta_min"] { parts.append("ETA \(eta) min") }
            ids.append(e.id)
        }
        return parts.joined(separator: ", ") + ChartModel.receipt(ids)
    }
    static func timeOrNot(_ e: EarshotEvent?, _ m: ChartModel) -> String {
        guard let e = e else { return ChartModel.notHeard }
        return "\(m.clock.clock(e.tMs)) (\(e.fields["method"] ?? ChartModel.srcLabel(e))) [\(e.id)]" + (e.needsConfirm ? " (confirm)" : "")
    }
    static func openItems(_ m: ChartModel) -> [String] {
        var L: [String] = []
        if !m.unlabeledTaps.isEmpty || !m.confirmItems.isEmpty || !m.gaps.isEmpty {
            L.append("")
            L.append("## Needs medic review")
            for t in m.unlabeledTaps { L.append("- Marked at \(m.clock.clock(t.tMs)), no label (\(t.tapSource ?? "tap")) [\(t.id)]") }
            for c in m.confirmItems { L.append("- Heard, please confirm: \(safeQuote(c.quote)) [\(c.id)]") }
            for g in m.gaps { L.append("- Audio gap at \(m.clock.clock(g.tMs)) (\(g.fields["duration_ms"] ?? "?") ms) [\(g.id)]") }
        }
        return L
    }
}
